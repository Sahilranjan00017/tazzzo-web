#!/usr/bin/env node
// Turns a finished `next build` (output: 'standalone') of apps/<app> into an Amplify Hosting "deployment specification"
// bundle at apps/<app>/.amplify-hosting (docs: "Using the Amplify Hosting deployment specification to configure build
// output"). Usage: node scripts/amplify/package-compute.mjs <storefront|admin>
//
// Why not Amplify's built-in Next.js adapter: its documented support range is Next.js 12-15 and this repo is on Next 16
// (proxy.ts, nonce CSP). With the deployment specification the compute runs Next's own standalone server, so
// next.config headers and src/proxy.ts execute inside Next exactly as in the container build.
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { selectRuntimeEnv } from './runtime-env.mjs'
import { validateRuntimeEnv } from './validate-runtime-env.mjs'

export const DEFAULT_RUNTIME = 'nodejs22.x'

/** The entrypoint Amplify starts. It loads the allow-listed runtime env, then hands over to Next's standalone server. */
export function entrypointSource(app) {
  return `// Generated by scripts/amplify/package-compute.mjs. Loads the allow-listed runtime variables, then starts Next.
'use strict'
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const values = JSON.parse(readFileSync(join(__dirname, 'runtime-env.json'), 'utf8'))
for (const [name, value] of Object.entries(values)) process.env[name] = value
process.env.NODE_ENV = 'production'
process.env.PORT = process.env.PORT || '3000'
process.env.HOSTNAME = '0.0.0.0'
process.env.NEXT_TELEMETRY_DISABLED = '1'
import('./apps/${app}/server.js').catch((error) => {
  console.error('failed to start', error && error.message)
  process.exit(1)
})
`
}

export function deployManifest({ nextVersion, runtime }) {
  return {
    version: 1,
    framework: { name: 'next-standalone', version: nextVersion },
    routes: [
      { path: '/_next/static/*', target: { kind: 'Static' } },
      { path: '/*', target: { kind: 'Compute', src: 'default' } },
    ],
    computeResources: [{ name: 'default', entrypoint: 'index.js', runtime }],
  }
}

function filesUnder(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name)
    return entry.isDirectory() ? filesUnder(path) : [path]
  })
}

/** The spellings of a secret the leak check looks for: plain, percent-encoded, JSON-escaped (also with escaped slashes), base64, base64url. */
export function leakVariants(value) {
  if (value.length < 8) return []
  const json = JSON.stringify(value).slice(1, -1)
  const b64 = Buffer.from(value).toString('base64')
  return [
    ...new Set([
      value,
      encodeURIComponent(value),
      json,
      json.replaceAll('/', '\\/'),
      b64,
      b64.replaceAll('+', '-').replaceAll('/', '_').replace(/=+$/, ''),
    ]),
  ].filter((v) => v.length >= 8)
}

/**
 * DEFENCE IN DEPTH, not a proof: fails if a secret VALUE (at least 8 characters) appears in a file below `dir` as plain text,
 * percent-encoded, JSON-escaped, base64 or base64url. It does NOT catch other encodings (hex, HTML entities, case changes),
 * a value split into pieces or computed at runtime, or a secret shorter than 8 characters. Names only in the error.
 */
export function assertNoSecretValuesIn(dir, secretValues) {
  const hits = []
  for (const file of filesUnder(dir)) {
    const text = readFileSync(file, 'utf8')
    for (const [name, value] of Object.entries(secretValues)) {
      if (leakVariants(value).some((variant) => text.includes(variant)))
        hits.push(`${name} in ${file}`)
    }
  }
  if (hits.length > 0) throw new Error(`secret value found in static output: ${hits.join('; ')}`)
}

export function packageCompute({
  root,
  app,
  env,
  runtime = DEFAULT_RUNTIME,
  validate = validateRuntimeEnv,
}) {
  const appDir = join(root, 'apps', app)
  const standalone = join(appDir, '.next', 'standalone')
  if (!existsSync(join(standalone, 'apps', app, 'server.js'))) {
    throw new Error(`no standalone build for ${app}: run "pnpm --filter ${app} build" first`)
  }
  const { values, secretNames } = selectRuntimeEnv(app, env)
  // The app's own production parser, before anything is written: a rule that would fail at runtime fails the build.
  validate({ root, app, values })

  const out = join(appDir, '.amplify-hosting')
  const compute = join(out, 'compute', 'default')
  const staticDir = join(out, 'static')
  rmSync(out, { recursive: true, force: true })
  mkdirSync(compute, { recursive: true })
  mkdirSync(join(staticDir, '_next'), { recursive: true })

  // Compute: Next's traced standalone tree (symlinks resolved so the bundle is self-contained), plus the assets the
  // standalone server expects beside it. The public/ files are served by the Next server itself.
  cpSync(standalone, compute, { recursive: true, dereference: true })
  cpSync(join(appDir, '.next', 'static'), join(compute, 'apps', app, '.next', 'static'), {
    recursive: true,
  })
  if (existsSync(join(appDir, 'public'))) {
    cpSync(join(appDir, 'public'), join(compute, 'apps', app, 'public'), { recursive: true })
  }
  // Static: hashed build assets, served by the CDN without invoking compute.
  cpSync(join(appDir, '.next', 'static'), join(staticDir, '_next', 'static'), { recursive: true })

  // index.js is CommonJS whatever package.json sits above the bundle (apps/storefront is "type": "module").
  if (existsSync(join(compute, 'package.json')))
    throw new Error('standalone root unexpectedly has a package.json')
  writeFileSync(join(compute, 'package.json'), '{"private":true,"type":"commonjs"}\n')
  writeFileSync(join(compute, 'index.js'), entrypointSource(app))
  writeFileSync(join(compute, 'runtime-env.json'), JSON.stringify(values), { mode: 0o600 })

  const nextVersion = JSON.parse(readFileSync(join(appDir, 'package.json'), 'utf8')).dependencies
    .next
  writeFileSync(
    join(out, 'deploy-manifest.json'),
    JSON.stringify(deployManifest({ nextVersion, runtime }), null, 2),
  )

  const secretValues = Object.fromEntries(secretNames.map((name) => [name, values[name]]))
  assertNoSecretValuesIn(staticDir, secretValues)
  assertNoSecretValuesIn(join(appDir, '.next', 'static'), secretValues)

  return { out, forwarded: Object.keys(values).sort(), secretNames, runtime }
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invokedDirectly) {
  const app = process.argv[2]
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
  try {
    const runtime = process.env.AMPLIFY_COMPUTE_RUNTIME || DEFAULT_RUNTIME
    const result = packageCompute({ root, app, env: process.env, runtime })
    const size = filesUnder(result.out).reduce((sum, f) => sum + statSync(f).size, 0)
    console.log(
      `packaged ${app} -> ${result.out} (${Math.round(size / 1e6)} MB, compute runtime ${result.runtime})`,
    )
    console.log(`runtime variables forwarded (names only): ${result.forwarded.join(', ')}`)
    console.log(`of which secret: ${result.secretNames.join(', ')}`)
  } catch (error) {
    console.error(`package-compute failed: ${error.message}`)
    process.exit(1)
  }
}
